import gradle_lock as lock


BODY = b'official artifact fixture\x00\xff'
HASH = hashlib.sha256(BODY).hexdigest()
SHA1 = hashlib.sha1(BODY).hexdigest()


def xml(group='org.jetbrains.kotlin', name='kotlin-stdlib', version='1.7.20',
        artifact=None, value=HASH, namespace=True):
    artifact = artifact or name + '-' + version + '.jar'
    attributes = (' xmlns="' + lock.NS + '" xmlns:xsi="' + lock.XSI + '"'
                  ' xsi:schemaLocation="' + lock.NS + ' ' + lock.NS + '/dependency-verification-1.3.xsd"') if namespace else ''
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<!-- generated fixture -->\n'
            '<verification-metadata' + attributes + '>'
            '<configuration><verify-metadata>true</verify-metadata>'
            '<verify-signatures>false</verify-signatures></configuration><components>'
            '<component group="' + group + '" name="' + name + '" version="' + version + '">'
            '<artifact name="' + artifact + '"><sha256 value="' + value + '" origin="Generated by Gradle"/>'
            '</artifact></component></components></verification-metadata>')


class FakeRepository:
    def __init__(self, sha256=True, sha1=True):
        self.calls = []
        self.sha256, self.sha1 = sha256, sha1

    def __call__(self, url, max_bytes):
        self.calls.append((url, max_bytes))
        if url.endswith('.sha256'):
            return HASH.encode() if self.sha256 else None
        if url.endswith('.sha1'):
            return SHA1.encode() if self.sha1 else None
        return BODY


class GradleLockTests(unittest.TestCase):
    def rejects(self, value):
        with self.assertRaises(lock.LockError):
            lock.validate_gradle_lock(value)

    def test_generated_namespace_and_comment(self):
        row = lock.validate_gradle_lock(xml())[0]
        self.assertEqual(row, dict(group='org.jetbrains.kotlin', name='kotlin-stdlib',
                                  version='1.7.20', artifact='kotlin-stdlib-1.7.20.jar', sha256=HASH))
        self.assertEqual(lock.validate_gradle_lock(xml(namespace=False)), [row])
        self.assertEqual(lock.validate_gradle_lock(xml(value=HASH.upper())), [row])

    def test_non_utf8_xml_and_encoded_doctype_rejected(self):
        self.rejects(xml().encode('utf-16'))
        self.rejects(xml().replace('<!-- generated fixture -->', '<!DOCTYPE x [<!ENTITY a \"hi\">]>').encode('utf-16'))

    def test_configuration_must_be_exact(self):
        for value in [xml().replace('<verify-metadata>true', '<verify-metadata>false'),
                      xml().replace('<verify-signatures>false', '<verify-signatures>true'),
                      xml().replace('<verify-signatures>false</verify-signatures>', ''),
                      xml().replace('</configuration>', '<verify-metadata>true</verify-metadata></configuration>')]:
            with self.subTest(value=value):
                self.rejects(value)

    def test_all_trust_or_unknown_extensions_rejected(self):
        for element in ['<trusted-artifacts/>', '<trusted-keys/>', '<ignored-keys/>',
                        '<key-servers/>', '<x:trusted-artifacts xmlns:x="urn:other"/>', '<unknown/>']:
            with self.subTest(element=element):
                self.rejects(xml().replace('</configuration>', element + '</configuration>'))

    def test_every_artifact_needs_exactly_one_sha256(self):
        checksum = '<sha256 value="' + HASH + '" origin="Generated by Gradle"/>'
        for replacement in ['', checksum + checksum, '<sha1 value="' + SHA1 + '"/>',
                            '<sha256 value="' + HASH + '"><also-trust value="' + 'b' * 64 + '"/></sha256>',
                            '<pgp value="abc"/>', '<sha256 value="bad"/>',
                            checksum.replace('/>', ' trusted="true"/>')]:
            with self.subTest(replacement=replacement):
                self.rejects(xml().replace(checksum, replacement))

    def test_second_unhashed_artifact_rejected(self):
        self.rejects(xml().replace('</component>', '<artifact name="kotlin-stdlib-1.7.20.pom"/></component>'))

    def test_duplicates_rejected(self):
        start, end = xml().index('<component '), xml().index('</component>') + len('</component>')
        self.rejects(xml().replace('</components>', xml()[start:end] + '</components>'))
        start, end = xml().index('<artifact '), xml().index('</artifact>') + len('</artifact>')
        self.rejects(xml().replace('</component>', xml()[start:end] + '</component>'))

    def test_empty_and_misplaced_components_rejected(self):
        self.rejects(xml().replace('<components>', '<components><sha256 value="' + HASH + '"/>'))
        first = xml().index('<component ')
        last = xml().index('</component>') + len('</component>')
        self.rejects(xml()[:first] + xml()[last:])
        self.rejects(xml().replace('</components>', '<component group="a" name="b" version="1"/></components>'))

    def test_path_dynamic_and_unexpected_extension_rejected(self):
        for arguments in [dict(group='../evil'), dict(group='org..evil'), dict(name='bad/name'),
                          dict(version='1.0-SNAPSHOT'), dict(version='1.+'), dict(version='latest.release'),
                          dict(artifact='../bad.jar'), dict(artifact='kotlin-stdlib-1.7.20.jar?x=1'),
                          dict(artifact='another-1.7.20.jar'), dict(artifact='kotlin-stdlib-1.7.20.zip')]:
            with self.subTest(arguments=arguments):
                self.rejects(xml(**arguments))

    def test_doctype_entities_namespace_schema_and_text_rejected(self):
        for value in [xml().replace('<verification-metadata', '<!DOCTYPE x [<!ENTITY a "hi">]><verification-metadata', 1),
                      xml().replace('<components>', '<components>unexpected'),
                      xml().replace('<artifact name', '<artifact xmlns="urn:foreign" name'),
                      xml().replace('dependency-verification-1.3.xsd', 'dependency-verification-9.9.xsd'),
                      xml().replace('<!-- generated fixture -->', '<?xml-stylesheet href="bad"?>'),
                      xml().replace('<components>', '<components unknown="true">')]:
            with self.subTest(value=value):
                self.rejects(value)

    def test_metadata_and_platform_classifier_supported(self):
        for filename in ['aapt2-8.4.0-11315950-linux.jar', 'aapt2-8.4.0-11315950.pom',
                         'aapt2-8.4.0-11315950.module']:
            rows = lock.validate_gradle_lock(xml(group='com.android.tools.build', name='aapt2',
                                                version='8.4.0-11315950', artifact=filename))
            self.assertTrue(lock.artifact_url(rows[0]).startswith(lock.GOOGLE))

    def test_exact_plugin_marker_authorities(self):
        android = lock.validate_gradle_lock(xml(group='com.android.library', name='com.android.library.gradle.plugin',
                                               version='8.4.0', artifact='com.android.library.gradle.plugin-8.4.0.pom'))[0]
        kotlin = lock.validate_gradle_lock(xml(group='org.jetbrains.kotlin.android', name='org.jetbrains.kotlin.android.gradle.plugin',
                                              artifact='org.jetbrains.kotlin.android.gradle.plugin-1.7.20.pom'))[0]
        self.assertEqual(lock.artifact_url(android), lock.GOOGLE + 'com/android/library/com.android.library.gradle.plugin/8.4.0/com.android.library.gradle.plugin-8.4.0.pom')
        self.assertEqual(lock.artifact_url(kotlin), lock.CENTRAL + 'org/jetbrains/kotlin/android/org.jetbrains.kotlin.android.gradle.plugin/1.7.20/org.jetbrains.kotlin.android.gradle.plugin-1.7.20.pom')
        self.assertEqual(lock.repository_for('com.google.testing.platform'), lock.GOOGLE)
        self.assertEqual(lock.repository_for('com.androidish'), lock.CENTRAL)

    def test_all_captured_entries_are_fetched_not_just_jars(self):
        original = xml()
        artifact = '<artifact name="kotlin-stdlib-1.7.20.pom"><sha256 value="' + HASH + '"/></artifact>'
        original = original.replace('</component>', artifact + '</component>')
        fake = FakeRepository()
        report = lock.review_lock(original, fetcher=fake, workers=1)
        self.assertEqual(report['artifact_count'], 2)
        self.assertEqual(len(fake.calls), 6)
        self.assertEqual({url.rsplit('/', 1)[-1] for url, _ in fake.calls if not url.endswith(('.sha1', '.sha256'))},
                         {'kotlin-stdlib-1.7.20.jar', 'kotlin-stdlib-1.7.20.pom'})

    def test_published_checksums_match_with_byte_comparison(self):
        fake = FakeRepository()
        report = lock.review_lock(xml(), fetcher=fake)
        self.assertEqual(lock.verify_review(xml(), report), report)
        item = report['artifacts'][0]
        self.assertEqual(item['method'], lock.METHOD)
        self.assertEqual([v['status'] for v in item['repository_published_checksums']], ['matched', 'matched'])
        self.assertEqual(item['downloaded_sha256'], HASH)

    def test_missing_sha256_sidecar_is_honest_fresh_byte_comparison(self):
        report = lock.review_lock(xml(), fetcher=FakeRepository(sha256=False))
        checks = report['artifacts'][0]['repository_published_checksums']
        self.assertEqual(checks[0]['status'], 'unavailable')
        self.assertEqual(checks[0]['http_status'], 404)
        self.assertEqual(checks[1]['status'], 'matched')
        self.assertIn('not independently authenticated publisher signatures', report['limitations'])
        lock.verify_review(xml(), report)

    def test_both_sidecars_missing_does_not_skip_artifact_hash(self):
        report = lock.review_lock(xml(), fetcher=FakeRepository(False, False))
        self.assertEqual(report['artifacts'][0]['downloaded_sha256'], HASH)
        lock.verify_review(xml(), report)
        with self.assertRaises(lock.LockError):
            lock.review_lock(xml(value='a' * 64), fetcher=FakeRepository(False, False))

    def test_missing_or_changed_official_artifact_is_fatal(self):
        for body in [None, b'changed', b'']:
            with self.subTest(body=body), self.assertRaises(lock.LockError):
                lock.review_lock(xml(), fetcher=lambda url, limit: body)

    def test_published_malformed_or_mismatch_fatal(self):
        for checksum in [b'bad', b'a' * 64, HASH.encode() + b' *wrong.jar', HASH.encode() + b'\nextra']:
            def bad_sidecar(url, limit):
                return checksum if url.endswith('.sha256') else BODY
            with self.subTest(checksum=checksum), self.assertRaises(lock.LockError):
                lock.review_lock(xml(), fetcher=bad_sidecar)

    def test_published_checksum_format(self):
        for suffix in ['', '  file.jar', ' *file.jar', '\n']:
            self.assertEqual(lock.parse_checksum((HASH.upper() + suffix).encode(), 'sha256', 'file.jar'), HASH)

    def test_evidence_rejects_wrong_xml_even_if_same_graph(self):
        report = lock.review_lock(xml(), fetcher=FakeRepository())
        with self.assertRaises(lock.LockError):
            lock.verify_review(xml() + '\n', report)

    def test_evidence_incomplete_duplicate_or_quarantine_fails(self):
        report = lock.review_lock(xml(), fetcher=FakeRepository())
        mutations = [lambda r: r.update(status='quarantined'), lambda r: r.update(artifact_count=0),
                     lambda r: r.update(artifacts=[]), lambda r: r['artifacts'].append(r['artifacts'][0]),
                     lambda r: r.update(graph_sha256='a' * 64), lambda r: r.update(limitations='publisher authenticated'),
                     lambda r: r.update(reviewed_at_utc='2026-01-01'), lambda r: r.update(schema_version=True)]
        for mutate in mutations:
            bad = copy.deepcopy(report)
            mutate(bad)
            with self.subTest(mutation=mutate), self.assertRaises(lock.LockError):
                lock.verify_review(xml(), bad)

    def test_evidence_bad_source_bytes_and_sidecar_rejected(self):
        report = lock.review_lock(xml(), fetcher=FakeRepository())
        mutations = [lambda i: i.update(final_url='https://mirror.invalid/a.jar'),
                     lambda i: i.update(method='gradle-cache-hash'),
                     lambda i: i.update(downloaded_sha256='a' * 64),
                     lambda i: i.update(size_bytes=True), lambda i: i.update(repository_published_checksums=[]),
                     lambda i: i['repository_published_checksums'][0].update(value='a' * 64),
                     lambda i: i['repository_published_checksums'][0].update(status='unavailable', http_status=500)]
        for mutate in mutations:
            bad = copy.deepcopy(report)
            mutate(bad['artifacts'][0])
            with self.subTest(mutation=mutate), self.assertRaises(lock.LockError):
                lock.verify_review(xml(), bad)

    def test_duplicate_json_fields_rejected(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'evidence.json'
            path.write_text('{"status":"quarantined","status":"independently-reviewed-checksum-lock"}')
            with self.assertRaises(lock.LockError):
                lock.read_review(path)

    def test_fetch_only_404_is_unavailable(self):
        url = lock.CENTRAL + 'a/b/1/b-1.jar.sha256'
        for status in [404, 403, 429, 500]:
            with patch('gradle_lock.urllib.request.build_opener') as build:
                build.return_value.open.side_effect = urllib.error.HTTPError(url, status, 'fixture', {}, None)
                if status == 404:
                    self.assertIsNone(lock.fetch(url, 4096))
                else:
                    with self.assertRaises(lock.LockError):
                        lock.fetch(url, 4096)

    def test_redirects_and_unofficial_urls_are_rejected(self):
        with self.assertRaises(lock.LockError):
            lock.fetch('https://mirror.invalid/a.jar', 100)
        with self.assertRaises(lock.LockError):
            lock._NoRedirect().redirect_request(urllib.request.Request(lock.CENTRAL + 'a.jar'),
                                                None, 302, '', {}, 'https://mirror.invalid/a.jar')

    def test_review_has_no_gradle_cache_dependency(self):
        with patch('pathlib.Path.read_bytes', side_effect=AssertionError('Unexpected local cache read')):
            report = lock.review_lock(xml(), fetcher=FakeRepository())
        self.assertEqual(report['artifact_count'], 1)

    def test_cli_failed_review_writes_no_success_file(self):
        with tempfile.TemporaryDirectory() as directory:
            source, output = Path(directory) / 'lock.xml', Path(directory) / 'review.json'
            source.write_text(xml())
            argv = ['gradle_lock.py', 'review', '--verification-file', str(source), '--output', str(output)]
            with patch('sys.argv', argv), patch('gradle_lock.review_lock', side_effect=lock.LockError('fixture failure')):
                with self.assertRaises(lock.LockError):
                    lock.main()
            self.assertFalse(output.exists())

    def test_cli_review_digest_pin_required(self):
        with tempfile.TemporaryDirectory() as directory:
            source, output = Path(directory) / 'lock.xml', Path(directory) / 'review.json'
            source.write_text(xml())
            output.write_text(json.dumps(lock.review_lock(xml(), fetcher=FakeRepository())))
            argv = ['gradle_lock.py', 'check-review', '--verification-file', str(source),
                    '--review-file', str(output), '--review-sha256', 'a' * 64]
            with patch('sys.argv', argv), self.assertRaises(lock.LockError):
                lock.main()
            argv[-1] = lock.sha256(output.read_bytes())
            with patch('sys.argv', argv), patch('builtins.print'):
                lock.main()


